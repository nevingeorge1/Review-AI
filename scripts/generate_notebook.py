    "class ASTFinding:\n",
    "    rule_id: str\n",
    "    title: str\n",
    "    category: str\n",
    "    severity: str\n",
    "    line_number: int\n",
    "    end_line: Optional[int]\n",
    "    description: str\n",
    "    recommendation: str\n",
    "    code_evidence: str\n",
    "    replacement_snippet: Optional[str] = None\n",
    "\n",
    "class ReviewAIASTVisitor(ast.NodeVisitor):\n",
    "    \"\"\"Single-pass deterministic AST visitor implementing key security & quality rules.\"\"\"\n",
    "    \n",
    "    def __init__(self, source_lines: List[str]):\n",
    "        self.source_lines = source_lines\n",
    "        self.findings: List[ASTFinding] = []\n",
    "        \n",
    "    def _get_snippet(self, node: ast.AST) -> str:\n",
    "        if hasattr(node, 'lineno') and 1 <= node.lineno <= len(self.source_lines):\n",
    "            return self.source_lines[node.lineno - 1].strip()\n",
    "        return \"\"\n",
    "\n",
    "    def visit_Call(self, node: ast.Call):\n",
    "        # RULE-001: eval() check\n",
    "        if isinstance(node.func, ast.Name) and node.func.id == 'eval':\n",
    "            self.findings.append(ASTFinding(\n",
    "                rule_id=\"RULE-001\",\n",
    "                title=\"Dangerous eval() Usage\",\n",
    "                category=\"security\",\n",
    "                severity=\"high\",\n",
    "                line_number=node.lineno,\n",
    "                end_line=getattr(node, 'end_lineno', node.lineno),\n",
    "                description=\"Dynamic execution of arbitrary Python expressions via eval() exposes remote code execution.\",\n",
    "                recommendation=\"Use ast.literal_eval() for safe literal parsing or json.loads() for JSON data.\",\n",
    "                code_evidence=self._get_snippet(node),\n",
    "                replacement_snippet=\"import ast\\nresult = ast.literal_eval(payload)\"\n",
    "            ))\n",
    "            \n",
    "        # RULE-006: pickle.loads() check\n",
    "        if isinstance(node.func, ast.Attribute) and node.func.attr == 'loads':\n",
    "            if isinstance(node.func.value, ast.Name) and node.func.value.id == 'pickle':\n",
    "                self.findings.append(ASTFinding(\n",
    "                    rule_id=\"RULE-006\",\n",
    "                    title=\"Insecure Deserialization (pickle.loads)\",\n",
    "                    category=\"security\",\n",
    "                    severity=\"high\",\n",
    "                    line_number=node.lineno,\n",
    "                    end_line=getattr(node, 'end_lineno', node.lineno),\n",
    "                    description=\"Unpickling untrusted data allows arbitrary code execution via __reduce__ payloads.\",\n",
    "                    recommendation=\"Use structured serialization like json.loads(), msgpack, or protobuf.\",\n",
    "                    code_evidence=self._get_snippet(node),\n",
    "                    replacement_snippet=\"import json\\ndata = json.loads(payload)\"\n",
    "                ))\n",
    "                \n",
    "        # RULE-014: SQL execute string formatting\n",
    "        if isinstance(node.func, ast.Attribute) and node.func.attr == 'execute':\n",
    "            if node.args and isinstance(node.args[0], (ast.JoinedStr, ast.BinOp)):\n",
    "                self.findings.append(ASTFinding(\n",
