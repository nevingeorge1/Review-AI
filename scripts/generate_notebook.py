    "                    title=\"SQL Injection via String Formatting\",\n",
    "                    category=\"security\",\n",
    "                    severity=\"high\",\n",
    "                    line_number=node.lineno,\n",
    "                    end_line=getattr(node, 'end_lineno', node.lineno),\n",
    "                    description=\"SQL query constructed using string formatting/f-strings vulnerable to SQL injection (CWE-89).\",\n",
    "                    recommendation=\"Use parameterized queries with placeholder bindings (?, %s, :param).\",\n",
    "                    code_evidence=self._get_snippet(node),\n",
    "                    replacement_snippet='cursor.execute(\"SELECT * FROM users WHERE username = %s\", (username,))'\n",
    "                ))\n",
    "        self.generic_visit(node)\n",
    "\n",
    "    def visit_FunctionDef(self, node: ast.FunctionDef):\n",
